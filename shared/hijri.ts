export interface HijriMonth {
  year: number;
  month: number;
  /** Its first day (YYYY-MM-DD), after the admins' adjustment. */
  start: string;
}

export interface HijriAdjustment {
  year: number;
  month: number;
  /** -1, 0 or +1 day. */
  days: number;
}

export const HIJRI_ADJUST_MAX = 1;

const msOf = (day: string) => Date.parse(`${day}T00:00:00Z`);
const addDays = (day: string, n: number) => new Date(msOf(day) + n * 86_400_000).toISOString().slice(0, 10);

/** Every month in the table, with the admins' adjustments applied. */
export function hijriMonths(adjustments: HijriAdjustment[] = []): HijriMonth[] {
  return UMM_AL_QURA.map((x) => {
    const [ym, start] = x.split(':');
    const [year, month] = ym.split('-').map(Number);
    const shift = adjustments.find((a) => a.year === year && a.month === month)?.days ?? 0;
    return { year, month, start: addDays(start, Math.max(-HIJRI_ADJUST_MAX, Math.min(HIJRI_ADJUST_MAX, shift))) };
  });
}

/** The Hijri month and day of a calendar day (YYYY-MM-DD), or null outside the table. */
export function hijriOf(day: string, months: HijriMonth[]): { year: number; month: number; day: number } | null {
  for (let i = months.length - 2; i >= 0; i--) {
    if (day >= months[i].start && day < months[i + 1].start) {
      const n = Math.round((msOf(day) - msOf(months[i].start)) / 86_400_000) + 1;
      return { year: months[i].year, month: months[i].month, day: n };
    }
  }
  return null;
}

/** Ramadan: the 9th month. */
export const isRamadan = (h: { month: number } | null) => h?.month === 9;
/** The first ten days of Dhul Hijjah (the 12th month), the day of Arafah among them. */
export const isFirstTenOfDhulHijjah = (h: { month: number; day: number } | null) => h?.month === 12 && h.day <= 10;
